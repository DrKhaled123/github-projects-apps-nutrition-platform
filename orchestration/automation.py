#!/usr/bin/env python3
"""
CI/CD Automation Module
Provides git hooks, webhooks, and automated triggers for CI/CD pipeline
"""

import json
import os
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional
from flask import Flask, request, jsonify
import threading


class CICDAutomation:
    """Handles automated CI/CD triggers and webhooks"""
    
    def __init__(self, config_path: str = "./orchestration/automation-config.json"):
        self.config = self._load_config(config_path)
        self.project_root = Path.cwd()
        self.git_hooks_dir = self.project_root / ".git" / "hooks"
        self.logs_dir = Path("orchestration/logs")
        self.logs_dir.mkdir(parents=True, exist_ok=True)
    
    def _load_config(self, config_path: str) -> Dict:
        """Load automation configuration"""
        default_config = {
            "git_hooks": {
                "pre_commit": {
                    "enabled": True,
                    "run_tests": True,
                    "run_linting": True,
                    "block_on_failure": True
                },
                "pre_push": {
                    "enabled": True,
                    "run_full_tests": True,
                    "run_security_scan": True,
                    "block_on_failure": True
                },
                "post_merge": {
                    "enabled": True,
                    "auto_deploy": False,
                    "notify": True
                }
            },
            "webhooks": {
                "enabled": True,
                "port": 8090,
                "secret": os.environ.get("WEBHOOK_SECRET", ""),
                "github": {
                    "enabled": True,
                    "events": ["push", "pull_request"]
                },
                "gitlab": {
                    "enabled": False,
                    "events": ["push", "merge_request"]
                }
            },
            "auto_deploy": {
                "enabled": True,
                "branches": ["main", "master", "production"],
                "require_tests": True,
                "require_review": False
            }
        }
        
        try:
            if Path(config_path).exists():
                with open(config_path, 'r') as f:
                    loaded_config = json.load(f)
                    default_config.update(loaded_config)
        except Exception as e:
            print(f"Warning: Could not load config, using defaults: {e}")
        
        return default_config
    
    def setup_git_hooks(self):
        """Install git hooks for automated checks"""
        print("\n" + "="*60)
        print("Setting up Git Hooks")
        print("="*60)
        
        if not self.git_hooks_dir.exists():
            print("⚠️  No .git directory found. Initialize git first.")
            return False
        
        hooks_to_setup = []
        
        # Pre-commit hook
        if self.config["git_hooks"]["pre_commit"]["enabled"]:
            hooks_to_setup.append(("pre-commit", self._create_pre_commit_hook()))
        
        # Pre-push hook
        if self.config["git_hooks"]["pre_push"]["enabled"]:
            hooks_to_setup.append(("pre-push", self._create_pre_push_hook()))
        
        # Post-merge hook
        if self.config["git_hooks"]["post_merge"]["enabled"]:
            hooks_to_setup.append(("post-merge", self._create_post_merge_hook()))
        
        # Install hooks
        for hook_name, hook_content in hooks_to_setup:
            hook_path = self.git_hooks_dir / hook_name
            
            try:
                with open(hook_path, 'w') as f:
                    f.write(hook_content)
                
                # Make executable
                os.chmod(hook_path, 0o755)
                
                print(f"✅ Installed {hook_name} hook")
            except Exception as e:
                print(f"❌ Failed to install {hook_name} hook: {e}")
                return False
        
        print("\n✅ All git hooks installed successfully!")
        return True
    
    def _create_pre_commit_hook(self) -> str:
        """Generate pre-commit hook script"""
        config = self.config["git_hooks"]["pre_commit"]
        
        return f'''#!/bin/sh
# Pre-commit hook - Auto-generated by CI/CD Automation
# Runs tests and linting before allowing commit

echo "🔍 Running pre-commit checks..."

FAILED=0

# Run linting
{f"""
if [ "{config['run_linting']}" = "True" ]; then
    echo "📝 Running linting..."
    python3 -m pylint --rcfile=.pylintrc $(git diff --cached --name-only --diff-filter=ACM | grep -E '\\.py$') 2>/dev/null
    if [ $? -ne 0 ]; then
        echo "❌ Linting failed"
        FAILED=1
    fi
fi
""" if config.get('run_linting') else ""}

# Run tests
{f"""
if [ "{config['run_tests']}" = "True" ]; then
    echo "🧪 Running tests..."
    python3 orchestration/testing_orchestrator.py --type unit --quick
    if [ $? -ne 0 ]; then
        echo "❌ Tests failed"
        FAILED=1
    fi
fi
""" if config.get('run_tests') else ""}

# Check if we should block
{f"""
if [ $FAILED -ne 0 ] && [ "{config['block_on_failure']}" = "True" ]; then
    echo ""
    echo "❌ Pre-commit checks failed! Commit blocked."
    echo "Fix the issues and try again, or use --no-verify to skip checks."
    exit 1
fi
""" if config.get('block_on_failure') else ""}

echo "✅ Pre-commit checks passed!"
exit 0
'''
    
    def _create_pre_push_hook(self) -> str:
        """Generate pre-push hook script"""
        config = self.config["git_hooks"]["pre_push"]
        
        return f'''#!/bin/sh
# Pre-push hook - Auto-generated by CI/CD Automation
# Runs full tests and security scans before allowing push

echo "🚀 Running pre-push checks..."

FAILED=0

# Run full test suite
{f"""
if [ "{config['run_full_tests']}" = "True" ]; then
    echo "🧪 Running full test suite..."
    python3 orchestration/testing_orchestrator.py --type all
    if [ $? -ne 0 ]; then
        echo "❌ Tests failed"
        FAILED=1
    fi
fi
""" if config.get('run_full_tests') else ""}

# Run security scan
{f"""
if [ "{config['run_security_scan']}" = "True" ]; then
    echo "🔒 Running security scan..."
    python3 -m bandit -r . -ll 2>/dev/null
    if [ $? -ne 0 ]; then
        echo "⚠️  Security issues found"
        FAILED=1
    fi
fi
""" if config.get('run_security_scan') else ""}

# Check if we should block
{f"""
if [ $FAILED -ne 0 ] && [ "{config['block_on_failure']}" = "True" ]; then
    echo ""
    echo "❌ Pre-push checks failed! Push blocked."
    echo "Fix the issues and try again, or use --no-verify to skip checks."
    exit 1
fi
""" if config.get('block_on_failure') else ""}

echo "✅ Pre-push checks passed!"
exit 0
'''
    
    def _create_post_merge_hook(self) -> str:
        """Generate post-merge hook script"""
        config = self.config["git_hooks"]["post_merge"]
        
        return f'''#!/bin/sh
# Post-merge hook - Auto-generated by CI/CD Automation
# Runs after successful merge

echo "🔄 Post-merge actions..."

# Auto-deploy if configured
{f"""
if [ "{config['auto_deploy']}" = "True" ]; then
    echo "🚀 Triggering auto-deployment..."
    python3 orchestration/main_orchestrator.py --mode full --async &
fi
""" if config.get('auto_deploy') else ""}

# Send notification
{f"""
if [ "{config['notify']}" = "True" ]; then
    echo "📧 Sending merge notification..."
    # Add your notification logic here
fi
""" if config.get('notify') else ""}

echo "✅ Post-merge actions completed!"
exit 0
'''
    
    def create_webhook_server(self):
        """Create Flask webhook server for external triggers"""
        if not self.config["webhooks"]["enabled"]:
            print("⚠️  Webhooks are disabled in config")
            return None
        
        app = Flask(__name__)
        
        @app.route('/webhook/<provider>', methods=['POST'])
        def webhook_handler(provider):
            """Handle incoming webhooks"""
            try:
                # Verify secret if configured
                secret = self.config["webhooks"]["secret"]
                if secret:
                    received_secret = request.headers.get('X-Webhook-Secret')
                    if received_secret != secret:
                        return jsonify({"error": "Invalid secret"}), 401
                
                # Parse payload
                payload = request.json
                
                # Log webhook
                log_entry = {
                    "timestamp": datetime.now().isoformat(),
                    "provider": provider,
                    "event": payload.get("event", "unknown"),
                    "payload": payload
                }
                
                log_file = self.logs_dir / f"webhooks_{datetime.now().strftime('%Y%m%d')}.log"
                with open(log_file, 'a') as f:
                    f.write(json.dumps(log_entry) + "\n")
                
                # Handle GitHub webhooks
                if provider == "github" and self.config["webhooks"]["github"]["enabled"]:
                    return self._handle_github_webhook(payload)
                
                # Handle GitLab webhooks
                elif provider == "gitlab" and self.config["webhooks"]["gitlab"]["enabled"]:
                    return self._handle_gitlab_webhook(payload)
                
                else:
                    return jsonify({"error": "Unsupported provider"}), 400
                
            except Exception as e:
                print(f"Webhook error: {e}")
                return jsonify({"error": str(e)}), 500
        
        @app.route('/trigger/<stage>', methods=['POST'])
        def manual_trigger(stage):
            """Manually trigger a pipeline stage"""
            try:
                # Run orchestrator in background
                subprocess.Popen([
                    sys.executable,
                    "orchestration/main_orchestrator.py",
                    "--stage", stage
                ])
                
                return jsonify({
                    "message": f"Triggered {stage} pipeline",
                    "status": "running"
                })
            except Exception as e:
                return jsonify({"error": str(e)}), 500
        
        return app
    
    def _handle_github_webhook(self, payload: Dict) -> tuple:
        """Handle GitHub webhook events"""
        event = payload.get("event") or request.headers.get('X-GitHub-Event')
        
        if event == "push":
            ref = payload.get("ref", "")
            branch = ref.split("/")[-1]
            
            # Check if branch should trigger deployment
            if branch in self.config["auto_deploy"]["branches"]:
                print(f"🚀 Push to {branch} - triggering deployment")
                
                # Run pipeline asynchronously
                subprocess.Popen([
                    sys.executable,
                    "orchestration/main_orchestrator.py",
                    "--mode", "full"
                ])
                
                return jsonify({
                    "message": "Deployment triggered",
                    "branch": branch
                }), 200
        
        elif event == "pull_request":
            action = payload.get("action")
            
            if action in ["opened", "synchronize"]:
                print(f"🔍 PR {action} - running checks")
                
                # Run tests and review
                subprocess.Popen([
                    sys.executable,
                    "orchestration/main_orchestrator.py",
                    "--mode", "test-and-review"
                ])
                
                return jsonify({
                    "message": "PR checks triggered"
                }), 200
        
        return jsonify({"message": "Event ignored"}), 200
    
    def _handle_gitlab_webhook(self, payload: Dict) -> tuple:
        """Handle GitLab webhook events"""
        # Similar to GitHub handler
        return jsonify({"message": "GitLab webhooks not fully implemented"}), 200
    
    def run_webhook_server(self):
        """Start the webhook server"""
        app = self.create_webhook_server()
        
        if app is None:
            return
        
        port = self.config["webhooks"]["port"]
        
        print("\n" + "="*60)
        print(f"🌐 Webhook Server Running on http://0.0.0.0:{port}")
        print("="*60)
        print(f"\nEndpoints:")
        print(f"  - POST /webhook/github   - GitHub webhooks")
        print(f"  - POST /webhook/gitlab   - GitLab webhooks")
        print(f"  - POST /trigger/<stage>  - Manual triggers")
        print("\nPress Ctrl+C to stop\n")
        
        try:
            app.run(host='0.0.0.0', port=port, debug=False, threaded=True)
        except KeyboardInterrupt:
            print("\n🛑 Webhook server stopped")


def main():
    """Main entry point"""
    automation = CICDAutomation()
    
    import sys
    
    if len(sys.argv) > 1:
        command = sys.argv[1]
        
        if command == "setup-hooks":
            automation.setup_git_hooks()
        elif command == "webhook-server":
            automation.run_webhook_server()
        else:
            print(f"Unknown command: {command}")
            print("Usage: python automation.py [setup-hooks|webhook-server]")
    else:
        print("Usage: python automation.py [setup-hooks|webhook-server]")


if __name__ == "__main__":
    main()
